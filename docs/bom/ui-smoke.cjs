/* Проверка на отдельном тестовом экземпляре с демонстрационными данными.
 * BOM_TEST_URL=http://127.0.0.1:18083 node docs/bom/ui-smoke.cjs
 * Нужен playwright. Скрипт создаёт свой черновик и удаляет его после проверки.
 */
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const url = process.env.BOM_TEST_URL;
if (!url) throw new Error('Укажите BOM_TEST_URL отдельного тестового экземпляра.');
(async()=>{
    const browser = await chromium.launch({headless:true});
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors=[];
    page.on('pageerror',err=>errors.push(err.message));
    const request=page.request;
    const get=async route=>{const r=await request.get(url+'/api/v1/bom'+route); assert(r.ok()); return r.json();};
    let draftId;
    try {
    const specs=await get('/specifications'), products=await get('/products');
    const base=specs.find(s=>s.productCode==='BOM-HOUSING' && s.revision===1);
    assert(base, 'Нужен исходный учебный корпус');
    const steel=products.find(p=>p.code==='BOM-STEEL'), bolt=products.find(p=>p.code==='BOM-BOLT'), paint=products.find(p=>p.code==='BOM-PAINT');
    const waitDetail=()=>page.locator('#bom-calc').waitFor();
    const screenshot=async name=>{await page.locator('.toast').last().waitFor({state:'hidden',timeout:10000}); await page.evaluate(()=>window.scrollTo(0,0)); await page.screenshot({path:path.join(__dirname,'screenshots',name),fullPage:true});};
        await page.goto(url+'/#/bom');
        await page.locator('#bom-specs a').first().waitFor();
        await page.locator('#bom-search').fill('нет такого изделия 999');
        assert((await page.locator('#bom-specs').innerText()).includes('ничего не найдено'));
        await page.locator('#bom-search').fill('корпус');
        await page.locator('#bom-status').selectOption('DRAFT');
        assert(!(await page.locator('#bom-specs').innerText()).includes('Утверждён'));
        await page.locator('#bom-search').fill('');
        await page.locator('#bom-status').selectOption('');
        await screenshot('01-overview.png');
        await page.goto(url+'/#/bom/'+base.id); await waitDetail();
        assert.equal(await page.locator('[data-add]').count(),0);
        await page.locator('[name="quantity"]').fill('3');
        await page.getByRole('button',{name:'Рассчитать потребность',exact:true}).click();
        await page.locator('#bom-results table').first().waitFor();
        const results=page.locator('#bom-results');
        assert.match(await results.innerText(),/3,75/);
        assert.match(await results.innerText(),/21/);
        const classOption=await page.locator('[name="classId"] option').evaluateAll(opts=>opts.find(o=>o.textContent.includes('BOM-MATERIALS')).value);
        await page.locator('[name="classId"]').selectOption(classOption);
        assert.match(await results.innerText(),/Условия изменились/);
        await page.getByRole('button',{name:'Рассчитать потребность',exact:true}).click();
        await results.locator('table').first().waitFor();
        assert.match(await results.innerText(),/3,75/);
        assert.equal(await results.locator('table').first().getByText('Болт М6',{exact:true}).count(),0);
        await results.locator('summary').click();
        await screenshot('02-calculation.png');
        await page.locator('[name="quantity"]').fill('2,5');
        await page.getByRole('button',{name:'Рассчитать потребность',exact:true}).click();
        await results.locator('table').first().waitFor();
        assert.match(await results.innerText(),/3,125/);
        await page.locator('[data-revise]').click();
        await page.locator('.modal [name="description"]').fill('Проверка интерфейса: увеличение расхода стали');
        await page.getByRole('button',{name:'Создать черновик',exact:true}).click();
        await page.waitForURL(u=>u.hash!==`#/bom/${base.id}`);
        draftId=Number(new URL(page.url()).hash.split('/').pop());
        await waitDetail();
        await page.locator('[data-edit="2"]').click();
        assert(await page.locator('[name="position"]').evaluate(el=>el.readOnly));
        // У материала не должно быть чужой версии кронштейна.
        assert.equal(await page.locator('[name="componentSpecificationId"] option').count(),1);
        await page.locator('.modal [name="quantity"]').fill('1');
        await page.getByRole('button',{name:'Сохранить изменение',exact:true}).click();
        await page.locator('.modal').waitFor({state:'hidden'}); await waitDetail();
        assert.match(await page.locator('#bom-detail').innerText(),/Заменён/);
        await page.locator('[data-exclude="3"]').click();
        await page.locator('[data-reset="3"]').waitFor();
        assert.match(await page.locator('.bom-changes').first().innerText(),/Убран из состава/);
        await page.locator('[name="quantity"]').fill('3');
        await page.locator('#bom-calc button').click();
        await results.locator('table').first().waitFor();
        const steelRow=results.locator('table').first().locator('tr').filter({hasText:'Листовая сталь'});
        assert.match(await steelRow.innerText(),/\b6\b/);
        await screenshot('03-draft-changes.png');
        await page.locator('[data-reset="3"]').click();
        await page.locator('.modal').getByRole('button',{name:'Вернуть как было',exact:true}).click();
        await page.locator('.modal').waitFor({state:'hidden'}); await waitDetail();
        await page.locator('[data-edit="3"]').waitFor();
        await page.locator('[data-add]').click();
        await page.locator('[name="componentId"]').selectOption(String(bolt.id));
        assert.equal(await page.locator('[name="componentSpecificationId"] option').count(),1);
        const bracket=products.find(p=>p.code==='BOM-BRACKET');
        await page.locator('[name="componentId"]').selectOption(String(bracket.id));
        assert((await page.locator('[name="componentSpecificationId"] option').count())>1);
        await page.locator('[name="componentSpecificationId"]').selectOption({index:1});
        await page.locator('[name="componentId"]').selectOption(String(paint.id));
        assert.equal(await page.locator('[name="componentSpecificationId"]').inputValue(),'');
        await page.locator('[name="position"]').fill('2');
        await page.locator('.modal [name="quantity"]').fill('0,1');
        await page.getByRole('button',{name:'Добавить в состав',exact:true}).click();
        await page.getByText('Этот номер уже занят.',{exact:false}).waitFor();
        await page.locator('[name="position"]').fill('4');
        await page.getByRole('button',{name:'Добавить в состав',exact:true}).click();
        await page.locator('.modal').waitFor({state:'hidden'}); await waitDetail();
        await page.locator('[data-edit="4"]').waitFor();
        const lines=await get(`/specifications/${draftId}/lines`);
        assert.equal(lines.find(l=>l.position===4).quantity,0.1);
        await page.locator('[data-exclude="4"]').click();
        await page.locator('.modal').getByRole('button',{name:'Убрать компонент',exact:true}).click();
        await page.locator('.modal').waitFor({state:'hidden'}); await waitDetail();
        await page.locator('[data-edit="4"]').waitFor({state:'hidden'});
        // Исключение/возврат не меняют исходную утверждённую версию.
        const original=await get(`/specifications/${base.id}/lines`);
        assert.equal(original.find(l=>l.position===2).quantity,0.25);
        await page.setViewportSize({width:900,height:1000});
        await waitDetail();
        assert(await page.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth), 'Страница не должна выходить за ширину окна');
        await screenshot('04-narrow.png');
        await page.locator('[data-remove]').click();
        await page.locator('.modal').getByRole('button',{name:'Удалить черновик',exact:true}).click();
        await page.waitForURL(u=>u.hash==='#/bom');
        assert(!(await get('/specifications')).some(s=>s.id===draftId)); draftId=null;
        assert.deepEqual(errors,[]);
        console.log('PASS: поиск, фильтр, расчёт всех/группы, дробное количество, новая версия, замена, исключение, возврат, зависимые поля, защита номера, добавление и удаление; исходный состав сохранён.');
    } finally {
        if(draftId) await request.delete(url+`/api/v1/bom/specifications/${draftId}`);
        await browser.close();
    }
})().catch(e=>{console.error(e);process.exitCode=1;});
